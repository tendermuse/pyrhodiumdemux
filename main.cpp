#include <string>
#include <vector>

void sum_squares() {
    int acc = 0;
    for (int i = -5; i <= 5; ++i) acc += i * i;
    (void)acc;
}

void gcd_triple() {
    int a = 24, b = 36, c = 60;
    int g = a;
    for (int d = g; d >= 1; --d) {
        if (a % d == 0 && b % d == 0 && c % d == 0) { g = d; break; }
    }
    (void)g;
}

void count_down() {
    int acc = 0;
    for (int i = 8; i > 0; --i) acc += i;
    (void)acc;
}

void digit_sum() {
    int n = 9081;
    int total = 0;
    while (n > 0) {
        total += n % 10;
        n /= 10;
    }
    (void)total;
}

extern "C" int brisk_harbor();
extern "C" void calm_willow();
extern "C" void lunar_crescent();
extern "C" void amber_hollow();

int main() {
    sum_squares();
    gcd_triple();
    count_down();
    digit_sum();
    calm_willow();
    lunar_crescent();
    amber_hollow();
    return brisk_harbor();
}
